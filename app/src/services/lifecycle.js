/**
 * ============================================================================
 *  services/lifecycle.js — состояние процесса для балансировщика
 * ============================================================================
 *  Когда копию приложения останавливают (обновление, уменьшение числа копий
 *  в Kubernetes, docker stop), она получает SIGTERM. Сначала копия
 *  переходит в режим «draining»: проверка готовности /healthz начинает
 *  отвечать 503, и балансировщик перестаёт присылать ей новые запросы. Уже
 *  начатые запросы (например, загрузка видео) спокойно дорабатывают, и
 *  только потом сервер закрывается (см. server.js). Так при уменьшении
 *  числа копий пользователи не получают ошибок.
 * ============================================================================
 */
let draining = false;

/** Копия выводится из балансировки: новых запросов ей больше не нужно. */
export function startDraining() {
  draining = true;
}

export function isDraining() {
  return draining;
}
