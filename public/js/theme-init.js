/* ============================================================================
   theme-init.js — выбор светлого/тёмного РЕЖИМА до отрисовки страницы
   ============================================================================
   Не путать с ТЕМОЙ оформления (Классическая, iCloud…): тема выбирается на
   сервере и подключается отдельным CSS-файлом, а режим (светлый/тёмный) —
   здесь, в браузере. Каждая тема поддерживает оба режима.

   Подключается синхронно в <head> (без defer), поэтому выполняется раньше,
   чем браузер нарисует страницу, — нет «вспышки» светлого режима у тех, кто
   выбрал тёмный.

   Приоритет выбора:
     1. выбор пользователя (кнопка ◐, сохраняется в localStorage);
     2. режим по умолчанию из настроек админки (атрибут data-default-mode);
     3. значение "auto" — следовать системной настройке ОС (prefers-color-scheme).

   Написано на ES5 без стрелочных функций — для максимальной совместимости.
   ============================================================================ */
(function () {
  var root = document.documentElement;
  var stored = null;
  try {
    stored = window.localStorage.getItem('color-mode');
  } catch (e) {
    /* localStorage может быть недоступен (приватный режим) — не страшно. */
  }
  var mode = stored || root.getAttribute('data-default-mode') || 'light';
  if (mode === 'auto') {
    mode = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  }
  root.setAttribute('data-mode', mode);
})();
