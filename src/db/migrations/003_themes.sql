-- Тема, выбранная пользователем в профиле. NULL — «как на сайте»
-- (тема по умолчанию из настроек администратора).
ALTER TABLE users ADD COLUMN theme VARCHAR(50);

-- Раньше цвета, шрифт и скругление всегда имели конкретные значения, и
-- при сохранении настроек они записывались в БД. Теперь пустое значение
-- означает «как в выбранной теме». Удаляем сохранённые значения, которые
-- совпадают со старыми умолчаниями, — иначе они перекрывали бы любую новую
-- тему (например, синяя шапка поверх светлой шапки темы iCloud).
-- Значения хранятся в JSON: строки — в кавычках, числа — без.
DELETE FROM settings
 WHERE (key = 'primary_color' AND value = '"#0052cc"')
    OR (key = 'header_bg'     AND value = '"#0747a6"')
    OR (key = 'header_text'   AND value = '"#ffffff"')
    OR (key = 'font_family'   AND value = '"system"')
    OR (key = 'border_radius' AND value = '6');
