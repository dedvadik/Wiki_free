/**
 * ============================================================================
 *  utils/http.js — мелкие HTTP-помощники, общие для всех маршрутов
 * ============================================================================
 */

/* ----------------------------------------------------------------------------
 * HttpError — ошибка с HTTP-статусом. Бросается в маршрутах:
 *     throw new HttpError(404, 'Страница не найдена');
 * Express 5 сам ловит исключения из async-обработчиков и передаёт их в
 * общий обработчик ошибок (middleware/errors.js), который покажет страницу
 * ошибки с нужным кодом.
 * ------------------------------------------------------------------------- */
export class HttpError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

/* ----------------------------------------------------------------------------
 * parseId — строгий разбор числового идентификатора из URL.
 * "42" → 42; "42abc", "-1", "" → ошибка 404 (а не странный SQL-запрос).
 * ------------------------------------------------------------------------- */
export function parseId(value) {
  if (!/^\d{1,9}$/.test(String(value ?? ''))) throw new HttpError(404, 'Не найдено');
  return Number(value);
}

/* ----------------------------------------------------------------------------
 * safeReturnTo — безопасный адрес для перенаправления после входа.
 * Разрешаем только локальные пути вида "/..." и запрещаем "//evil.com"
 * (браузер воспринял бы это как внешний сайт) — защита от open redirect.
 * ------------------------------------------------------------------------- */
export function safeReturnTo(url, fallback = '/') {
  return typeof url === 'string' && url.startsWith('/') && !url.startsWith('//') && !url.startsWith('/\\')
    ? url
    : fallback;
}

/* ----------------------------------------------------------------------------
 * backUrl — «вернуться туда, откуда пришли» (заголовок Referer), но только
 * в пределах нашего сайта. В Express 5 убрали res.redirect('back'), поэтому
 * реализуем сами.
 * ------------------------------------------------------------------------- */
export function backUrl(req, fallback = '/') {
  const referer = req.get('Referer');
  if (!referer) return fallback;
  try {
    const url = new URL(referer);
    return url.host === req.get('Host') ? safeReturnTo(url.pathname + url.search + url.hash, fallback) : fallback;
  } catch {
    return fallback;
  }
}

/* ----------------------------------------------------------------------------
 * regenerateSession — промис-обёртка над req.session.regenerate.
 * При входе в систему создаём НОВУЮ сессию с новым идентификатором:
 * защита от атаки «фиксация сессии» (злоумышленник не сможет заранее
 * подсунуть жертве известный ему идентификатор сессии).
 * ------------------------------------------------------------------------- */
export function regenerateSession(req) {
  return new Promise((resolve, reject) => {
    req.session.regenerate((err) => (err ? reject(err) : resolve()));
  });
}
